const LANGS = ['en', 'hi', 'bn', 'te', 'ta', 'mr', 'kn', 'gu', 'pa'];

function updateFile(filePath) {
  let content = fs.readFileSync(filePath, 'utf-8');

  LANGS.forEach((lang) => {
    // Look for `"lang": {` or `lang: {`
    const regex = new RegExp(`(["']?${lang}["']?\\s*:\\s*\\{[\\s\\S]*?)(\\n\\s*\\}(?:\\s*,|\\s*\\n\\s*\\};))`);
    const match = content.match(regex);
    if (!match) {
      console.error(`Could not locate section for ${lang} in ${filePath}`);
      return;
    }

    const entriesToAdd = [];
    Object.entries(BATCH).forEach(([key, translations]) => {
      const val = translations[lang] || translations.en;
      // check if key already exists in this language block
      const hasKey = new RegExp(`["']?${key}["']?\\s*:`).test(match[1]);
      if (!hasKey) {
        const escaped = val.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
        entriesToAdd.push(`    "${key}": '${escaped}',`);
      }
    });

    if (entriesToAdd.length > 0) {
      const insertion = '\n' + entriesToAdd.join('\n');
      content = content.replace(regex, `$1${insertion}$2`);
    }
  });

  fs.writeFileSync(filePath, content, 'utf-8');
  console.log(`Updated ${filePath}`);
}

updateFile(ROOT_I18N);
updateFile(BACKUP_I18N);

// Verify with dynamic import
async function verify() {
  const fileUrl = pathToFileURL(ROOT_I18N).href;
  const mod = await import(fileUrl + '?t=' + Date.now());
  const translations = mod.TRANSLATIONS;
  const baseKeys = Object.keys(translations.en);
  console.log(`Verified total keys in en: ${baseKeys.length}`);

  let allGood = true;
  LANGS.forEach((lang) => {
    const langKeys = Object.keys(translations[lang] || {});
    const missing = baseKeys.filter((k) => !langKeys.includes(k));
    const empty = baseKeys.filter((k) => !translations[lang][k] || translations[lang][k].trim() === '');
    console.log(`Language [${lang}]: ${langKeys.length} keys, Missing: ${missing.length}, Empty: ${empty.length}`);
    if (missing.length > 0 || empty.length > 0) {
      allGood = false;
    }
  });

  if (allGood) {
    console.log('SUCCESS: All 9 languages have 100% key and content parity!');
  } else {
    console.error('FAILURE: Discrepancies found.');
    process.exit(1);
  }
}

