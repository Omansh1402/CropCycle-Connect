const i18nPath = path.resolve('src/lib/i18nData.js');
let source = fs.readFileSync(i18nPath, 'utf8');

// We import the current TRANSLATIONS
import('../src/lib/i18nData.js').then((mod) => {
  const currentTranslations = mod.TRANSLATIONS;
  const langs = Object.keys(currentTranslations);

  console.log('Current languages:', langs);

  // Merge keys
  langs.forEach((lang) => {
    Object.entries(NEW_KEYS).forEach(([key, langMap]) => {
      const val = langMap[lang] || langMap.en;
      currentTranslations[lang][key] = val;
    });
  });

  console.log('New en key count:', Object.keys(currentTranslations.en).length);
  console.log('New bn key count:', Object.keys(currentTranslations.bn).length);

  // Re-serialize TRANSLATIONS in i18nData.js
  const startIdx = source.indexOf('export const TRANSLATIONS = {');
  if (startIdx === -1) {
    console.error('Could not find TRANSLATIONS in i18nData.js');
    process.exit(1);
  }

  // Find the end of TRANSLATIONS by searching for export const CROP_TRANSLATIONS or similar
  const endIdx = source.indexOf('export const CROP_TRANSLATIONS = {');
  if (endIdx === -1) {
    console.error('Could not find CROP_TRANSLATIONS in i18nData.js');
    process.exit(1);
  }

  const newTranslationsStr = 'export const TRANSLATIONS = ' + JSON.stringify(currentTranslations, null, 2) + ';\n\n';
  const newSource = source.slice(0, startIdx) + newTranslationsStr + source.slice(endIdx);

  fs.writeFileSync(i18nPath, newSource, 'utf8');
  console.log('Successfully updated src/lib/i18nData.js!');

  // Also sync to backup project
  const backupPath = path.resolve('backup project/CropCycle-Connect/src/lib/i18nData.js');
  fs.writeFileSync(backupPath, newSource, 'utf8');
  console.log('Successfully synced to backup project/CropCycle-Connect/src/lib/i18nData.js!');
});
