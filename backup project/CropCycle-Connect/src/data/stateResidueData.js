/**
 * Retrieve state statistics safely.
 */
export function getStateResidueData(stateName) {
  if (!stateName) return null;
  const clean = stateName.trim().toLowerCase();
  for (const [key, val] of Object.entries(STATE_RESIDUE_STATISTICS)) {
    if (key.toLowerCase() === clean) return val;
  }
  return null;
}

/**
 * Retrieve crop types available for a specific state.
 */
export function getResidueTypesForState(stateName) {
  const data = getStateResidueData(stateName);
  if (!data || !Array.isArray(data.crops) || data.crops.length === 0) {
    return [];
  }
  return data.crops.map((c) => c.residueType);
}

/**
 * Calculates live supply vs demand analytics distinguishing agricultural estimates
 * from live CropCycle Connect platform inventory.
 *
 * Prevents double counting by tracking allocated quantities between active compatible listings and requirements.
 */
export function calculateStatePlatformMetrics(stateName, residueTypeFilter, listings = [], buyers = []) {
  const stateStats = getStateResidueData(stateName);

  // 1. Annual Statewide Agricultural Estimates (from DES/MNRE)
  let totalProduction = 0;
  let availableSurplus = 0;
  let technicallyCollectable = 0;
  let existingUses = 0;
  let potentiallyAvailable = 0;
  let hasAgriculturalData = false;

  if (stateStats && stateStats.crops && stateStats.crops.length > 0) {
    hasAgriculturalData = true;
    if (!residueTypeFilter || residueTypeFilter === 'All') {
      totalProduction = stateStats.totalResidueTonnes || 0;
      availableSurplus = stateStats.surplusResidueTonnes || 0;
      technicallyCollectable = stateStats.collectableResidueTonnes || 0;
      existingUses = stateStats.existingUsesTonnes || 0;
      potentiallyAvailable = stateStats.remainingAvailableTonnes || 0;
    } else {
      const crop = stateStats.crops.find(
        (c) => c.residueType.toLowerCase() === residueTypeFilter.toLowerCase()
      );
      if (crop) {
        totalProduction = crop.residueGeneratedTonnes || 0;
        availableSurplus = crop.surplusResidueTonnes || 0;
        technicallyCollectable = crop.collectableResidueTonnes || 0;
        existingUses = crop.existingUsesTonnes || 0;
        potentiallyAvailable = crop.remainingAvailableTonnes || 0;
      }
    }
  }

  // 2. Platform Supply: Active farmer listings in this state
  const stateListings = listings.filter((l) => {
    const st = (l.state || '').toLowerCase().trim();
    const matchesState = !stateName || st === stateName.toLowerCase().trim();
    const matchesResidue =
      !residueTypeFilter ||
      residueTypeFilter === 'All' ||
      (l.residueType || l.residue_type || '').toLowerCase().trim() === residueTypeFilter.toLowerCase().trim();
    const isActive = (l.status || '').toLowerCase() === 'active';
    return matchesState && matchesResidue && isActive;
  });

  const platformSupply = Number(
    stateListings.reduce((sum, l) => sum + Number(l.quantity || l.quantity_tonnes || 0), 0).toFixed(1)
  );

  // 3. Platform Demand: Active buyer requirements seeking this residue or in this state
  const stateBuyers = buyers.filter((b) => {
    const isAvail = b.available !== false && (b.availabilityStatus || b.availability_status || '').toLowerCase() !== 'no';
    if (!isAvail) return false;

    let accepts = [];
    if (Array.isArray(b.acceptedTypes)) accepts = b.acceptedTypes;
    else if (Array.isArray(b.accepted_types)) accepts = b.accepted_types;
    else if (typeof b.accepted_types === 'string') accepts = b.accepted_types.split(',');

    const matchesResidue =
      !residueTypeFilter ||
      residueTypeFilter === 'All' ||
      accepts.some((t) => t.toLowerCase().trim() === residueTypeFilter.toLowerCase().trim());

    const bState = (b.state || '').toLowerCase().trim();
    const matchesState = !stateName || bState === stateName.toLowerCase().trim();

    return matchesResidue && matchesState;
  });

  const platformDemand = Number(
    stateBuyers.reduce((sum, b) => sum + Number(b.requiredQuantity || b.required_quantity_tonnes || 0), 0).toFixed(1)
  );

  // 4. Deterministic Non-Double-Counted Matching Allocation
  // Avoid counting the same farmer lot twice or satisfying more than a buyer's batch demand.
  const listingPool = stateListings.map((l) => ({
    id: l.id,
    remainingQty: Number(l.quantity || l.quantity_tonnes || 0),
    residueType: (l.residueType || l.residue_type || '').toLowerCase().trim(),
  }));

  const buyerPool = stateBuyers.map((b) => {
    let accepted = [];
    if (Array.isArray(b.acceptedTypes)) accepted = b.acceptedTypes;
    else if (Array.isArray(b.accepted_types)) accepted = b.accepted_types;
    else if (typeof b.accepted_types === 'string') accepted = b.accepted_types.split(',');

    return {
      id: b.id,
      unmetDemand: Number(b.requiredQuantity || b.required_quantity_tonnes || 0),
      acceptedTypes: accepted.map((t) => t.toLowerCase().trim()),
    };
  });

  let matchedQuantity = 0;

  for (const buyer of buyerPool) {
    if (buyer.unmetDemand <= 0) continue;

    for (const lot of listingPool) {
      if (lot.remainingQty <= 0) continue;

      const isCompatible = buyer.acceptedTypes.includes(lot.residueType);
      if (isCompatible) {
        const allocate = Math.min(lot.remainingQty, buyer.unmetDemand);
        matchedQuantity += allocate;
        lot.remainingQty -= allocate;
        buyer.unmetDemand -= allocate;

        if (buyer.unmetDemand <= 0) break;
      }
    }
  }

  matchedQuantity = Number(matchedQuantity.toFixed(1));
  const unmetDemand = Number(Math.max(0, platformDemand - matchedQuantity).toFixed(1));
  const availableUnmatchedSupply = Number(Math.max(0, platformSupply - matchedQuantity).toFixed(1));

  // External Reference Price
  let priceRef = null;
  if (residueTypeFilter && VERIFIED_PRICE_REFERENCES[residueTypeFilter]) {
    priceRef = VERIFIED_PRICE_REFERENCES[residueTypeFilter];
  }

  return {
    stateName,
    residueTypeFilter: residueTypeFilter || 'All',
    hasAgriculturalData,
    reportingYear: stateStats?.reportingYear || '2023-24',
    source: stateStats?.source || 'DES Agricultural Statistics at a Glance',
    sourceUrl: stateStats?.sourceUrl || 'https://agricoop.nic.in',
    methodology: stateStats?.methodology || 'Gross residue computed using ICAR NPMCR ratios',
    dataUnavailableReason: stateStats?.dataUnavailableReason || null,
    estimatedExternalMarketDemand: stateStats?.estimatedExternalMarketDemand || null,
    externalDemandNote: stateStats?.externalDemandNote || null,

    // A & B: State-level agricultural estimates
    totalProduction,
    availableSurplus,
    technicallyCollectable,
    existingUses,
    potentiallyAvailable,

    // C, D, E, F, G: Live platform ledger
    platformSupply,
    platformDemand,
    matchedQuantity,
    unmetDemand,
    availableUnmatchedSupply,

    // Price Benchmark
    priceReference: priceRef,
  };
}


